#!/usr/bin/env node
// Writes src/data/cloud9.ts from a directory of derived web images.
//
//   node scripts/build-cloud9.mjs <derived-dir>
//
// <derived-dir> holds one folder per run (sept-11/, sept-27/), each with
// <name>.webp (2400px) and <name>.thumb.webp (800px) per frame. The same
// folders, plus the original JPEGs, are what the ZimaOS box serves at
// photos.akvaithi.page — the photos are far too big to ship through Vercel.
// macOS-only: dimensions come from `sips`.
import { readdirSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { join } from "node:path";

const dir = process.argv[2];
if (!dir) {
  console.error("usage: build-cloud9.mjs <derived-dir>");
  process.exit(1);
}

const out = {};
for (const run of readdirSync(dir).filter((d) => !d.startsWith(".")).sort()) {
  const thumbs = readdirSync(join(dir, run))
    .filter((f) => f.endsWith(".thumb.webp"))
    .sort();
  const frames = [];
  for (const t of thumbs) {
    const info = execFileSync("sips", ["-g", "pixelWidth", "-g", "pixelHeight", join(dir, run, t)], {
      encoding: "utf8",
    });
    const w = Number(info.match(/pixelWidth: (\d+)/)[1]);
    const h = Number(info.match(/pixelHeight: (\d+)/)[1]);
    frames.push([t.replace(/\.thumb\.webp$/, ""), w, h]);
  }
  out[run] = frames;
  console.log(`${run}: ${frames.length} frames`);
}

const body = Object.entries(out)
  .map(
    ([run, frames]) =>
      `  ${JSON.stringify(run)}: [\n${frames.map((f) => `    ${JSON.stringify(f)},`).join("\n")}\n  ],`
  )
  .join("\n");

writeFileSync(
  "src/data/cloud9.frames.ts",
  `// Generated by scripts/build-cloud9.mjs. Do not edit by hand.
// [file name without extension, thumbnail width, thumbnail height]
export const FRAMES: Record<string, [name: string, w: number, h: number][]> = {
${body}
};
`
);
